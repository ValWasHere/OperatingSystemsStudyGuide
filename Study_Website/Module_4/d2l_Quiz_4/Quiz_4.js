// Get the button:
let mybutton = document.getElementById("topBtn");
// When the user scrolls down 20px from the top of the document, show the button
window.onscroll = function() {scrollFunction()};
function scrollFunction() {(document.body.scrollTop > 20 || document.documentElement.scrollTop > 20) ? mybutton.style.display = "block" : mybutton.style.display = "none";}
// When the user clicks on the button, scroll to the top of the document
function topFunc() {
  document.body.scrollTop = 0; // For Safari
  document.documentElement.scrollTop = 0; // For Chrome, Firefox, IE and Opera
} 
//Reset all the inline colors of the buttons
function clearAllBtns(){
    document.querySelectorAll('.btns').forEach(btn => {
        btn.style.backgroundColor = 'darkblue';
        btn.style.color = 'snow';
    });
}